from pathlib import Path
import json, sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pyspark.ml.recommendation import ALSModel
from pyspark.sql import functions as F
from src.config import load_config, get_spark_session
from src.data.loader import load_movielens_1m
from src.data.preprocessor import movie_popularity
from src.recommender.als_model import split_ratings
from src.recommender.recommender import recommend_for_users
from src.evaluation.evaluator import rmse, ranking_metrics, group_precision
from src.fairness.metrics import group_disparity, project_fairness_score
from src.diversity.diversity_metrics import catalog_coverage, intra_list_genre_diversity
from src.recommender.reranker import rerank

config = load_config()
spark = get_spark_session("FairLens Evaluation", config)
try:

    users, movies, ratings = load_movielens_1m(spark, config["paths"]["raw_data"])
    train, test = split_ratings(ratings, config["als"]["seed"])
    model = ALSModel.load(str(Path(config["paths"]["model_dir"]) / "als"))
    
    predicted = model.transform(test).dropna()
    k = config["evaluation"]["top_k"]
    threshold = config["evaluation"]["relevance_threshold"]
    
    candidates = recommend_for_users(model, train, test.select("user_id").distinct(), k * config["reranking"]["candidate_multiplier"])
    recs = candidates.filter(F.col("rank") <= k).cache()
    total_recs = max(recs.count(), 1)
    
    quality = {"rmse": rmse(predicted), **ranking_metrics(recs, test, k, threshold)}
    gender = group_precision(recs, test, users, "gender", k, threshold)
    age = group_precision(recs, test, users, "age", k, threshold)
    
    pop = movie_popularity(train).select("movie_id", "popularity_group")
    exposure = {r["popularity_group"]: r["count"] / total_recs for r in recs.join(pop, "movie_id").groupBy("popularity_group").count().collect()}
    
    candidate_rows = candidates.join(movies, "movie_id").join(pop, "movie_id").orderBy("user_id", "rank").collect()
    by_user = {}
    for row in candidate_rows:
        by_user.setdefault(row.user_id, []).append(row.asDict())
        
    fair_rows = []
    for user_id, items in by_user.items():
        for item in rerank(items, config["reranking"], k):
            fair_rows.append((user_id, int(item["movie_id"]), int(item["rank"]), float(item["prediction"])))
            
    fair = spark.createDataFrame(fair_rows, ["user_id", "movie_id", "rank", "prediction"]).cache()
    total_fair = max(fair.count(), 1)
    
    fair_quality = ranking_metrics(fair, test, k, threshold)
    fair_gender = group_precision(fair, test, users, "gender", k, threshold)
    fair_exposure = {r["popularity_group"]: r["count"] / total_fair for r in fair.join(pop, "movie_id").groupBy("popularity_group").count().collect()}
    
    catalog = {r.movie_id for r in movies.select("movie_id").collect()}
    fair_items = fair.join(movies, "movie_id").select("movie_id", "genres").collect()
    baseline_items = recs.join(movies, "movie_id").select("movie_id", "genres").collect()
    
    diversity = {
        "baseline_genre_diversity": intra_list_genre_diversity([r.genres for r in baseline_items]),
        "fairlens_genre_diversity": intra_list_genre_diversity([r.genres for r in fair_items]),
        "baseline_catalog_coverage": catalog_coverage({r.movie_id for r in baseline_items}, catalog),
        "fairlens_catalog_coverage": catalog_coverage({r.movie_id for r in fair_items}, catalog)
    }
    
    report = {
        "dataset": {"users": users.count(), "movies": movies.count(), "ratings": ratings.count()},
        "baseline": quality,
        "fairlens": fair_quality,
        "group_precision": {"baseline_gender": gender, "fairlens_gender": fair_gender, "age": age},
        "gender_precision_disparity": {"baseline": group_disparity(gender), "fairlens": group_disparity(fair_gender)},
        "project_fairness_score": {"baseline": project_fairness_score(group_disparity(gender)), "fairlens": project_fairness_score(group_disparity(fair_gender))},
        "popularity_exposure": {"baseline": exposure, "fairlens": fair_exposure},
        "diversity": diversity,
        "note": "Generated by run_evaluation.py from the configured dataset and weights."
    }
    
    out = Path(config["paths"]["results_dir"])
    out.mkdir(parents=True, exist_ok=True)
    (out / "baseline_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))
finally:
    spark.stop()

